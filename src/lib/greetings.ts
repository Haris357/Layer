// A line that stays stable for a while (changes per minute), seeded so it
// doesn't flicker on every render but still feels alive.
export function pickLine(seed: number): string {
  const i = Math.abs(seed) % GREETING_LINES.length
  return GREETING_LINES[i] ?? GREETING_LINES[0] ?? ''
}
