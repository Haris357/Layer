// Fill in the name, or drop the placeholder cleanly when there's no name set.
export function fillName(template: string, name: string): string {
  if (name) return template.replace(/\{name\}/g, name)
  return (
    template
      .replace(/,?\s*\{name\}/g, '')
      .replace(/\s+([?!.])/g, '$1')
      .trim() || 'Welcome back'
  )
}

